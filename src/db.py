import os
import re
from pathlib import Path

from sqlalchemy import create_engine, event, text

ROOT = Path(__file__).resolve().parents[1]


def database_url():
    return os.getenv('DATABASE_URL', f"sqlite:///{(ROOT / 'data' / 'warehouse.db').as_posix()}")


def get_engine(url=None):
    engine = create_engine(url or database_url(), pool_pre_ping=True)
    if engine.dialect.name == 'sqlite':
        @event.listens_for(engine, 'connect')
        def configure(dbapi_connection, _):
            dbapi_connection.isolation_level = None
            dbapi_connection.execute('PRAGMA foreign_keys=ON')
            dbapi_connection.execute('PRAGMA busy_timeout=30000')
            dbapi_connection.execute('PRAGMA cache_size=-32768')

        @event.listens_for(engine, 'begin')
        def begin(conn):
            conn.exec_driver_sql('BEGIN')
    return engine


def sql_statements(filename, dialect):
    sql = (ROOT / 'sql' / filename).read_text(encoding='utf-8')
    if dialect == 'sqlite':
        sql = sql.replace('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                          'INTEGER PRIMARY KEY AUTOINCREMENT')
        sql = re.sub(r'CREATE OR REPLACE VIEW\s+([A-Za-z_][A-Za-z0-9_]*)\s+AS',
                     r'DROP VIEW IF EXISTS \1; CREATE VIEW \1 AS', sql, flags=re.IGNORECASE)
    return [s.strip() for s in sql.split(';') if s.strip()]


def execute_file(conn, filename):
    for statement in sql_statements(filename, conn.dialect.name):
        conn.execute(text(statement))
