CREATE TABLE IF NOT EXISTS dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year INTEGER NOT NULL,
    quarter INTEGER NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name VARCHAR(12) NOT NULL,
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    day_name VARCHAR(12) NOT NULL,
    is_weekend BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id VARCHAR(32) NOT NULL,
    city VARCHAR(150) NOT NULL,
    state VARCHAR(2) NOT NULL,
    region VARCHAR(20) NOT NULL,
    UNIQUE (customer_unique_id, city, state)
);
CREATE TABLE IF NOT EXISTS dim_product (
    product_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(32) NOT NULL UNIQUE,
    category_name VARCHAR(100) NOT NULL,
    product_weight_g INTEGER CHECK (product_weight_g >= 0),
    product_length_cm INTEGER CHECK (product_length_cm >= 0)
);
CREATE TABLE IF NOT EXISTS dim_seller (
    seller_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id VARCHAR(32) NOT NULL UNIQUE,
    city VARCHAR(150) NOT NULL,
    state VARCHAR(2) NOT NULL,
    region VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS fact_sales (
    sales_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key INTEGER NOT NULL REFERENCES dim_date(date_key),
    customer_key INTEGER NOT NULL REFERENCES dim_customer(customer_key),
    product_key INTEGER NOT NULL REFERENCES dim_product(product_key),
    seller_key INTEGER NOT NULL REFERENCES dim_seller(seller_key),
    order_id VARCHAR(32) NOT NULL,
    order_item_id INTEGER NOT NULL CHECK (order_item_id > 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents >= 0),
    freight_cents BIGINT NOT NULL CHECK (freight_cents >= 0),
    total_revenue_cents BIGINT NOT NULL,
    CHECK (total_revenue_cents = unit_price_cents * quantity + freight_cents),
    UNIQUE (order_id, order_item_id)
);
CREATE INDEX IF NOT EXISTS ix_sales_date ON fact_sales(date_key);
CREATE INDEX IF NOT EXISTS ix_sales_customer ON fact_sales(customer_key);
CREATE INDEX IF NOT EXISTS ix_sales_product ON fact_sales(product_key);
CREATE INDEX IF NOT EXISTS ix_sales_seller ON fact_sales(seller_key);
CREATE TABLE IF NOT EXISTS etl_runs (
    run_id VARCHAR(36) PRIMARY KEY,
    started_at VARCHAR(32) NOT NULL,
    finished_at VARCHAR(32),
    status VARCHAR(12) NOT NULL,
    summary_json TEXT,
    error TEXT
);
CREATE TABLE IF NOT EXISTS etl_item_audit (
    source_row INTEGER PRIMARY KEY,
    order_id VARCHAR(32),
    order_item_id VARCHAR(30),
    disposition VARCHAR(80) NOT NULL,
    price_cents BIGINT,
    freight_cents BIGINT
);
